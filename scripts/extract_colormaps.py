#!/usr/bin/env python3
"""Generate core/colormaps.js from the colormap data embedded in the reference preview.html.

Run once (the output is committed):
    python3 scripts/extract_colormaps.py /path/to/preview.html
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SRC = ROOT.parent / "src/geozarr_pyramid_maker/templates/preview.html"


def main(argv):
    src = Path(argv[1]) if len(argv) > 1 else DEFAULT_SRC
    m = re.search(r'<script id="config" type="application/json">(.*?)</script>', src.read_text(), re.S)
    if not m:
        sys.exit(f"no embedded config in {src}")
    cfg = json.loads(m.group(1))
    compact = lambda o: json.dumps(o, separators=(",", ":"))
    out = [
        "// Generated by scripts/extract_colormaps.py from the reference preview.html config; do not edit.",
        "// COLORMAPS: name -> 11 RGB stops. COLORMAP_GROUPS: picker groups (source core = matplotlib, cmocean, cmasher).",
        f"const RAMP = {compact(cfg['ramp'])};",
        f"const COLORMAPS = {compact(cfg['colormaps'])};",
        "const COLORMAP_GROUPS = " + compact(cfg["colormap_groups"]) + ";",
        "",
    ]
    (ROOT / "core/colormaps.js").write_text("\n".join(out))
    print(f"wrote core/colormaps.js ({len(cfg['colormaps'])} maps)")


if __name__ == "__main__":
    main(sys.argv)
